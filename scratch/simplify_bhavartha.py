def replace_bhavartha(file_path, data_dict):
    if not os.path.exists(file_path):
        return

    with open(file_path, 'r', encoding='utf-8') as f:
        content = f.read()

    def replacer(m):
        verse_num = int(m.group(1))
        full_section = m.group(0)
        
        if verse_num not in data_dict:
            return full_section
        
        para = data_dict[verse_num]
        
        bh_pattern = re.compile(
            r'(\*\*भावार्थः:\*\*\s*)([^\n]+(?:\n[^\n]+)*?)(\n\n)',
            re.DOTALL
        )
        new_section = bh_pattern.sub(
            lambda mm: f"{mm.group(1)}{para}\n\n",
            full_section,
            count=1
        )
        return new_section
    
    verse_section_pattern = re.compile(
        r'<a id="meaning-(\d+)"></a>.*?(?=<a id="meaning-\d+">|\Z)',
        re.DOTALL
    )
    new_content = verse_section_pattern.sub(replacer, content)

    with open(file_path, 'w', encoding='utf-8') as f:
        f.write(new_content)
    
    print(f"Updated {file_path}")

